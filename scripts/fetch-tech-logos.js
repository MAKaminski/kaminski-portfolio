// Vendors the Skills-section logos into public/images/logos/tech/ and writes the
// name -> path map to src/data/techLogos.ts.
//
// Why: src/components/TechLogos.tsx used to hotlink ~80 SVGs and favicons from
// cdn.jsdelivr, worldvectorlogo and vendor /favicon.ico URLs. Lighthouse counted
// them as third-party cookies (Cloudflare __cf_bm on four of them), console
// errors (CORP-blocked and 404 favicons) and inspector issues — the whole
// best-practices gap — plus ~80 requests and ~300 KB on every home-page load.
//
// Sources, in order of preference:
//   1. simple-icons (npm, CC0 1.0) — monochrome paths; we set the brand hex when it
//      reads on #060606 and white otherwise.
//   2. devicon (MIT) — colour marks simple-icons no longer carries (Java, C#, AWS,
//      Oracle, Salesforce). Fetched once by hand from cdn.jsdelivr and committed.
//   3. Nothing. The skill name is rendered next to the icon anyway, so a missing
//      icon is a missing icon, not a broken image or a hotlink.
//
// Run: node scripts/fetch-tech-logos.js   (after `npm ci`; simple-icons is a devDependency)
const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, '..', 'public', 'images', 'logos', 'tech');
const MAP = path.join(__dirname, '..', 'src', 'data', 'techLogos.ts');

// Skill name (as written in src/components/Skills.tsx) -> simple-icons slug.
const SIMPLE = {
  SQL: 'mysql', Python: 'python', TypeScript: 'typescript', R: 'r', Rust: 'rust',
  'Node.js': 'nodedotjs', FastAPI: 'fastapi', PostgreSQL: 'postgresql', Redis: 'redis',
  GraphQL: 'graphql', Supabase: 'supabase', NeonDB: 'neon', Prisma: 'prisma', MongoDB: 'mongodb',
  React: 'react', Tailwind: 'tailwindcss', GCP: 'googlecloud', Docker: 'docker',
  Kubernetes: 'kubernetes', Serverless: 'serverless', Vercel: 'vercel', GitHub: 'github',
  'GitHub Actions': 'githubactions', Snowflake: 'snowflake', BigQuery: 'googlebigquery',
  Airflow: 'apacheairflow', Looker: 'looker', Claude: 'claude', 'Claude Code': 'claudecode',
  Cursor: 'cursor', DeepSeek: 'deepseek', Kimi: 'kimi', LangChain: 'langchain',
  MCP: 'modelcontextprotocol', 'Hugging Face': 'huggingface', TensorFlow: 'tensorflow',
  PyTorch: 'pytorch', 'SAP S/4HANA': 'sap', QuickBooks: 'quickbooks', Brex: 'brex',
  Stripe: 'stripe', 'Google Search Console': 'googlesearchconsole',
  'Google Analytics': 'googleanalytics', PostHog: 'posthog', Mixpanel: 'mixpanel',
  HubSpot: 'hubspot', Jira: 'jira', Confluence: 'confluence', Linear: 'linear', Notion: 'notion',
  Airtable: 'airtable', Figma: 'figma', Lucid: 'lucid', Resend: 'resend', Shopify: 'shopify',
};

// Skill name -> devicon file already committed under public/images/logos/tech/.
const DEVICON = {
  Java: 'java', 'C#': 'csharp', AWS: 'amazonwebservices', 'Oracle Hyperion': 'oracle',
  Salesforce: 'salesforce', Canva: 'canva',
};

function luminance(hex) {
  const n = parseInt(hex, 16);
  const c = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}

(async () => {
  const si = await import('simple-icons');
  const bySlug = new Map(Object.values(si).map((i) => [i.slug, i]));
  fs.mkdirSync(OUT, { recursive: true });
  const map = {};
  const missing = [];

  for (const [name, slug] of Object.entries(SIMPLE)) {
    const icon = bySlug.get(slug);
    if (!icon) { missing.push(`${name} (simple-icons: ${slug})`); continue; }
    // Brand colour if it reads on a #060606 ground, white otherwise.
    const fill = luminance(icon.hex) >= 0.18 ? `#${icon.hex}` : '#ffffff';
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="${fill}"><path d="${icon.path}"/></svg>\n`;
    fs.writeFileSync(path.join(OUT, `${slug}.svg`), svg);
    map[name] = `/images/logos/tech/${slug}.svg`;
  }
  for (const [name, slug] of Object.entries(DEVICON)) {
    if (!fs.existsSync(path.join(OUT, `${slug}.svg`))) { missing.push(`${name} (devicon: ${slug}.svg not committed)`); continue; }
    map[name] = `/images/logos/tech/${slug}.svg`;
  }

  const lines = Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  fs.writeFileSync(
    MAP,
    `// GENERATED by scripts/fetch-tech-logos.js — do not edit by hand.\n` +
      `// Skill name -> self-hosted logo. simple-icons (CC0) and devicon (MIT); see the script.\n` +
      `export const techLogos: Record<string, string> = {\n${lines.join('\n')}\n};\n`
  );
  console.log(`tech logos: ${Object.keys(map).length} written, ${missing.length} without an icon`);
  if (missing.length) console.log('  no icon (name renders alone): ' + missing.join(', '));
})().catch((e) => { console.error(e); process.exit(1); });
